package org.broken.arrow.library.database.construct.query.builder.table.constraint;

import org.broken.arrow.library.database.construct.query.builder.table.constraint.expression.DefaultExpression;
import org.broken.arrow.library.database.construct.query.builder.table.constraint.expression.UpdateAction;
import org.broken.arrow.library.database.utility.DatabaseType;

import javax.annotation.Nonnull;
/**
 * Represents common SQL constraints and provides factory methods for creating them.
 * <p>
 * This class is designed to simplify the construction of SQL column or table constraints
 * by providing static factory methods for frequently used constraint types such as
 * {@code PRIMARY KEY}, {@code NOT NULL}, {@code UNIQUE}, and {@code FOREIGN KEY}.
 * </p>
 * <p>
 * Constraints are stored as raw SQL fragments and can be used when building
 * SQL table creation statements or altering table definitions.
 * </p>
 *
 * <strong>Equality and Hashing:</strong>
 * Two {@link SQLConstraints} instances are considered equal if their SQL string values match exactly.
 *
 * @see #primaryKey()
 * @see #notNull()
 * @see #unique()
 */
public class SQLConstraints {
  /** SQL keyword for default value constraints. */
  public static final String DEFAULT = "DEFAULT";
  /** The raw SQL value representing the constraint. */
  private final String constraint;

  /**
   * Creates a new SQL constraint with the given SQL fragment.
   *
   * @param constraint the SQL constraint string (must not be {@code null})
   */
  public SQLConstraints(@Nonnull final String constraint) {
    this.constraint = constraint;
  }

  /**
   * Returns a {@code NULL} constraint.
   *
   * @return a nullable constraint
   */
  public static SQLConstraints nullable() {
    return new SQLConstraints("NULL");
  }

  /**
   * Returns a {@code NOT NULL} constraint.
   *
   * @return a not-null constraint
   */
  public static SQLConstraints notNull() {
    return new SQLConstraints("NOT NULL");
  }

  /**
   * Returns a {@code PRIMARY KEY} constraint.
   *
   * @return a primary key constraint
   */
  public static SQLConstraints primaryKey() {
    return new SQLConstraints("PRIMARY KEY");
  }

  /**
   * Returns a composite {@code PRIMARY KEY} constraint.
   *
   * @param columns the columns to include in the primary key
   * @return a primary key constraint for multiple columns
   */
  public static SQLConstraints primaryKeys(String... columns) {
    return new SQLConstraints("PRIMARY KEY (" + String.join(", ", columns) + ")");

  }

    /**
     * Returns an {@code AUTO_INCREMENT} constraint.
     *
     * @param type the database type you running
     * @return an auto-increment constraint
     */
    public static SQLConstraints autoIncrement(final DatabaseType type) {
      switch (type) {
        case SQLITE:
          return new SQLConstraints("AUTOINCREMENT");
        case POSTGRESQL:
          return new SQLConstraints("GENERATED BY DEFAULT AS IDENTITY");
        case H2:
        case MYSQL:
        default:
          return new SQLConstraints("AUTO_INCREMENT");
      }
    }

  /**
   * Returns a {@code UNIQUE} constraint.
   *
   * @return a unique constraint
   */
  public static SQLConstraints unique() {
    return new SQLConstraints("UNIQUE");
  }

  /**
   * Returns a {@code DEFAULT} constraint using a standard SQL expression, function, or keyword.
   * <p>
   * The resulting SQL will not quote the expression. For example, passing
   * {@link DefaultExpression#CURRENT_TIMESTAMP} results in {@code DEFAULT CURRENT_TIMESTAMP}.
   * </p>
   *
   * @param expression the predefined expression to set as the default
   * @return a default value constraint
   */
  public static SQLConstraints defaultVal(@Nonnull final DefaultExpression expression) {
    return new SQLConstraints(DEFAULT + " " + expression.getExpression());
  }

  /**
   * Returns a {@code DEFAULT} constraint with a literal string value.
   * <p>
   * The provided string is automatically wrapped in single quotes, and any internal single
   * quotes are escaped to prevent SQL injection or syntax errors. For example, passing
   * {@code "O'Connor"} results in {@code DEFAULT 'O''Connor'}.
   * </p>
   *
   * @param literal the literal string to set as the default value
   * @return a default value constraint containing the quoted string
   */
  public static SQLConstraints defaultVal(String literal) {
    String escaped = literal.replace("'", "''");
    return new SQLConstraints(DEFAULT + " '" + escaped + "'");
  }

  /**
   * Returns a {@code DEFAULT} constraint with the specified integer value.
   *
   * @param value the integer to set as the default value
   * @return a default value constraint
   */
  public static SQLConstraints defaultVal(int value) {
    return new SQLConstraints(DEFAULT + " " + value);
  }

  /**
   * Returns a {@code DEFAULT} constraint with the specified boolean value.
   * <p>
   * The boolean is converted to its standard SQL keyword representation
   * ({@code TRUE} or {@code FALSE}).
   * </p>
   *
   * @param value the boolean to set as the default value
   * @return a default value constraint
   */
  public static SQLConstraints defaultVal(boolean value) {
    return new SQLConstraints(DEFAULT + " " + (value ? "TRUE" : "FALSE"));
  }

  /**
   * Returns a {@code CHECK} constraint with the specified condition.
   *
   * @param condition the check condition
   * @return a check constraint
   */
  public static SQLConstraints check(String condition) {
    return new SQLConstraints("CHECK(" + condition + ")");
  }



  /**
   * Returns an {@code ON UPDATE} action constraint for a column.
   * <p>
   * This is used in conjunction with timestamps to automatically update a column
   * when a row is modified (e.g., {@code ON UPDATE CURRENT_TIMESTAMP}).
   * </p>
   *
   * @param action the predefined timestamp action to execute on update
   * @return an on-update action constraint
   */
  public static SQLConstraints onUpdate(@Nonnull final UpdateAction action) {
    return new SQLConstraints("ON UPDATE " + action.getAction());
  }

  /**
   * Returns a {@code UNIQUE} constraint for a specific column.
   *
   * @param column the column name
   * @return a unique key constraint
   */
  public static SQLConstraints uniqueKey(String column) {
    return new SQLConstraints("UNIQUE (" + column + ")");
  }

  /**
   * Gets the raw SQL definition for this constraint.
   *
   * @return the SQL constraint string
   */
  public String getConstraint() {
    return toString();
  }

  /**
   * Gets the raw SQL definition for this constraint.
   *
   * @return the SQL constraint string
   */
  @Override
  public String toString() {
    return constraint;
  }


  /**
   * Checks if this constraint is a {@code PRIMARY KEY}.
   *
   * @param o the object to check
   * @return {@code true} if the given object is a primary key constraint, otherwise {@code false}
   */
  public static boolean isPrimary(Object o) {
    if (o == null || SQLConstraints.class != o.getClass()) return false;

    SQLConstraints that = (SQLConstraints) o;
    return that.constraint.startsWith("PRIMARY KEY");

  }

  /**
   * Checks if this constraint is a {@code AUTO_INCREMENT}.
   *
   * @param constraints the object to check
   * @return {@code true} if the given object is an auto increment constraint, otherwise {@code false}
   */
  public static boolean isAutoIncrement(SQLConstraints constraints) {
    if(constraints == null) return false;
    return constraints.constraint.startsWith("AUTOINCREMENT") || constraints.constraint.startsWith("AUTO_INCREMENT") || constraints.constraint.startsWith("GENERATED BY DEFAULT AS IDENTITY");

  }

  /**
   * Compares this constraint to another for equality based on their SQL string values.
   *
   * @param o the object to compare
   * @return {@code true} if both constraints have the same SQL string value
   */
  @Override
  public boolean equals(Object o) {
    if (this == o) return true;
    if (o == null || getClass() != o.getClass()) return false;

    SQLConstraints that = (SQLConstraints) o;
    return constraint.equals(that.constraint);
  }

  /**
   * Returns a hash code based on the SQL string value.
   *
   * @return the hash code
   */
  @Override
  public int hashCode() {
    return constraint.hashCode();
  }
}